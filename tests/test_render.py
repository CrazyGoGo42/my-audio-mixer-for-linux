import re
import unittest

from audiomixer.config import Channel, ChannelState, MixerState
from audiomixer.render import needs_restart, render_routes, render_sinks

CHS = [Channel("default", "Default_Audio", "Desktop", ("KP_1", "KP_4", "KP_7")),
       Channel("music", "Music_Audio", "Music", ("KP_3", "KP_6", "KP_9")),
       Channel("voice", "Voice_Chat", "Voice Chat", ("-", "-", "-"))]


def state(**eq):
    s = MixerState({"A1": "@default", "A2": None, "A3": None, "A4": None},
                   {c.key: ChannelState() for c in CHS}, ["A1"], "@auto")
    for key, (bass, treble) in eq.items():
        s.channels[key].bass, s.channels[key].treble = bass, treble
    return s


def modules(text):
    """Split the rendered context.modules into one string per module."""
    body = text.split("context.modules = [", 1)[1]
    return [m for m in re.split(r"\n    \{", body) if "name = libpipewire-module" in m]


class RenderSinksTest(unittest.TestCase):
    def setUp(self):
        self.out = render_sinks(CHS, state(music=(6.5, -3.0)))
        self.mods = modules(self.out)

    def module_for(self, node_name):
        hits = [m for m in self.mods if f'node.name = "{node_name}"' in m]
        self.assertEqual(len(hits), 1, node_name)
        return hits[0]

    def test_one_module_per_channel_plus_ee_return_mic_and_all_audio(self):
        self.assertEqual(len(self.mods), len(CHS) + 3)
        for name in ("Default_Audio", "Music_Audio", "Voice_Chat", "EE_Return", "Mic_In", "All_Audio"):
            self.module_for(name)

    def test_every_module_is_nofail(self):
        self.assertTrue(all("flags = [ nofail ]" in m for m in self.mods))

    def test_props_blocks_are_single_line(self):
        for line in self.out.splitlines():
            if re.search(r"\.props = \{", line):
                self.assertEqual(line.count("{"), line.count("}"), line)

    def test_channels_are_builtin_filter_chains_without_ladspa(self):
        m = self.module_for("Music_Audio")
        self.assertIn("libpipewire-module-filter-chain", m)
        self.assertIn("label = bq_lowshelf", m)
        self.assertIn("label = bq_highshelf", m)
        self.assertNotIn("ladspa", self.out)

    def test_channel_sink_is_named_after_its_label(self):
        self.assertIn('node.description = "Voice Chat Audio"', self.module_for("Voice_Chat"))

    def test_outputs_and_internal_inputs_are_not_autoconnected(self):
        for name in ("Default_Audio_out", "Music_Audio_out", "Voice_Chat_out",
                     "EE_Return_out", "Mic_In_in", "All_Audio_in"):
            props = re.search(r'\{ node\.name = "' + name + r'"[^}]*\}', self.out)
            self.assertIsNotNone(props, name)
            self.assertIn("node.autoconnect = false", props.group(0), name)

    def test_our_sinks_never_win_default_output(self):
        for name in ("Default_Audio", "Music_Audio", "EE_Return"):
            props = re.search(r'\{ node\.name = "' + name + r'" media\.class = "Audio/Sink"[^}]*\}', self.out)
            self.assertIn("priority.session = 1", props.group(0), name)

    def test_mic_and_all_audio_are_sources_apps_can_pick(self):
        for name in ("Mic_In", "All_Audio"):
            self.assertRegex(self.out, r'\{ node\.name = "' + name + r'" media\.class = "Audio/Source"')

    def test_eq_gains_come_from_state(self):
        m = self.module_for("Music_Audio")
        self.assertRegex(m, r'label = bq_lowshelf control = \{[^}]*"Gain" = 6\.5')
        self.assertRegex(m, r'label = bq_highshelf control = \{[^}]*"Gain" = -3\.0')
        self.assertRegex(self.module_for("Default_Audio"), r'bq_lowshelf control = \{[^}]*"Gain" = 0\.0')


class NeedsRestartTest(unittest.TestCase):
    def test_eq_only_change_needs_no_restart(self):
        old = render_sinks(CHS, state())
        self.assertFalse(needs_restart(old, render_sinks(CHS, state(music=(4.0, -2.5)))))

    def test_channel_list_change_needs_restart(self):
        old = render_sinks(CHS, state())
        self.assertTrue(needs_restart(old, render_sinks(CHS[:2], state())))

    def test_missing_old_file_needs_restart(self):
        self.assertTrue(needs_restart(None, render_sinks(CHS, state())))


class RenderRoutesTest(unittest.TestCase):
    def test_routes_render_matches_previous_output(self):
        out = render_routes({"Music_Audio": [("application.process.binary", "spotify"),
                                             ("application.name", 'Odd "Name"')]}, "Default_Audio")
        self.assertEqual(out, GOLDEN_ROUTES)


GOLDEN_ROUTES = """\
# Generated by audio-routes-apply — do not edit by hand.
# Edit ~/.config/audio-mixer/routes.json and rerun audio-routes-apply.
#
# How this works: the first rule is a catch-all that sends EVERY app to the
# Default channel (attenuated and safe). Later rules are more specific and
# override it, pulling known apps onto their own channel. Because the target
# is set at stream creation, an app is born on the right sink every time --
# no race, and nothing ever escapes to the hardware at full volume.

pulse.rules = [
    # Catch-all: anything with an app name or binary -> Default.
    {
        matches = [
            { application.name = "~.+" }
            { application.process.binary = "~.+" }
        ]
        actions = { update-props = { target.object = "Default_Audio" } }
    }
    {
        matches = [
            { application.process.binary = "spotify" }
            { application.name = "Odd \\"Name\\"" }
        ]
        actions = { update-props = { target.object = "Music_Audio" } }
    }
]
"""


